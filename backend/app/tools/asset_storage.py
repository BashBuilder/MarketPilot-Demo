"""Publish generated assets to durable storage and resolve them back to a file.

Generation still writes a local working copy: the Designer verifies that file,
and an edit needs the bytes. Storage decides what URI goes into the package, so
the frontend can load the asset without access to this process's disk.

Two backends exist: ``local`` keeps the existing relative-path behaviour and
``cloudinary`` uploads the file and records the returned ``secure_url``.
"""

from pathlib import Path
from typing import Protocol

from app.core.config import Settings
from app.core.errors import ToolError
from app.tools.image_models import GeneratedImage, ImageGenerator, Size


class AssetStorage(Protocol):
    """Durable store for generated bytes, addressed by the URI saved in the DB."""

    async def publish(self, image: GeneratedImage) -> str: ...

    async def localize(self, uri: str) -> Path: ...


def relative_uri(path: Path, root: Path) -> str:
    """Prefer a portable path relative to the asset directory when possible."""
    resolved = path.resolve()
    try:
        return resolved.relative_to(root.resolve()).as_posix()
    except ValueError:
        return resolved.as_posix()


class LocalAssetStorage:
    """Keep assets on the process filesystem and store relative URIs."""

    def __init__(self, root: Path) -> None:
        self._root = root

    async def publish(self, image: GeneratedImage) -> str:
        return relative_uri(image.path, self._root)

    async def localize(self, uri: str) -> Path:
        """Resolve a local URI, refusing any path outside the asset directory."""
        if "://" in uri:
            raise ToolError(
                "local asset storage cannot resolve a remote URI",
                retryable=False,
                details={"uri": uri},
            )
        root = self._root.resolve()
        candidate = Path(uri)
        resolved = (candidate if candidate.is_absolute() else root / candidate).resolve()
        if not resolved.is_relative_to(root):
            raise ToolError(
                f"image path must be inside the asset directory: {uri}",
                details={"uri": uri, "asset_dir": str(root)},
            )
        if not resolved.is_file():
            raise ToolError(f"image not found: {uri}", details={"uri": uri})
        return resolved


class StoredImageGenerator:
    """Publish whatever the configured image backend just produced."""

    def __init__(self, inner: ImageGenerator, storage: AssetStorage) -> None:
        self._inner = inner
        self._storage = storage

    async def generate(
        self,
        prompt: str,
        negative_prompt: str,
        seed: int,
        size: Size,
    ) -> GeneratedImage:
        image = await self._inner.generate(prompt, negative_prompt, seed, size)
        return await self._publish(image)

    async def edit(self, image_path: Path | str, instruction: str) -> GeneratedImage:
        # A revision is seeded from a stored package, so the source may already
        # be a remote URI: fetch it back to a local working copy before editing.
        local = await self._storage.localize(str(image_path))
        image = await self._inner.edit(local, instruction)
        return await self._publish(image)

    async def _publish(self, image: GeneratedImage) -> GeneratedImage:
        uri = await self._storage.publish(image)
        return image.model_copy(update={"uri": uri})


def build_asset_storage(settings: Settings) -> AssetStorage:
    """Select the backend named by ``ASSET_STORAGE`` or fail before a run starts."""
    if settings.asset_storage == "local":
        return LocalAssetStorage(settings.asset_dir)

    if settings.asset_storage == "cloudinary":
        from app.tools.cloudinary_storage import CloudinaryAssetStorage

        cloud_name = (settings.cloudinary_cloud_name or "").strip()
        api_key = (
            settings.cloudinary_api_key.get_secret_value() if settings.cloudinary_api_key else ""
        )
        api_secret = (
            settings.cloudinary_api_secret.get_secret_value()
            if settings.cloudinary_api_secret
            else ""
        )
        if not cloud_name or not api_key or not api_secret:
            raise RuntimeError(
                "ASSET_STORAGE=cloudinary requires CLOUDINARY_CLOUD_NAME, "
                "CLOUDINARY_API_KEY and CLOUDINARY_API_SECRET"
            )
        return CloudinaryAssetStorage(
            cloud_name=cloud_name,
            api_key=api_key,
            api_secret=api_secret,
            asset_dir=settings.asset_dir,
            folder=settings.cloudinary_folder,
            timeout=settings.cloudinary_timeout_seconds,
        )

    raise RuntimeError(f"unsupported ASSET_STORAGE: {settings.asset_storage}")
